def get_platform_catalog() -> list[PlatformResourceDescriptor]:
    return list(_CATALOG)


def get_non_queryable_surfaces() -> list[NonQueryableSurface]:
    return list(_NON_QUERYABLE)


def get_descriptor(resource_key: str) -> PlatformResourceDescriptor | None:
    for descriptor in _CATALOG:
        if descriptor.resource_key == resource_key:
            return descriptor
    return None


def catalog_resource_keys() -> set[str]:
    return {descriptor.resource_key for descriptor in _CATALOG}
