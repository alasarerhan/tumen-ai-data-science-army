def _descriptor(
    resource_key: str,
    label: str,
    *,
    scope: str = "workspace",
    backing_source: str,
    queryable_fields: list[str],
    filterable_fields: list[str] | None = None,
    sortable_fields: list[str] | None = None,
    relationships: list[str] | None = None,
    default_limit: int = 20,
    freshness: str = "request-time",
    required_role: str = "member",
    redacted_fields: list[str] | None = None,
    available_actions: list[str] | None = None,
    canonical_ui: str | None = None,
    owner_module: str,
    resolver: str | None,
    tags: list[str],
    not_exposed_reason: str | None = None,
) -> PlatformResourceDescriptor:
    return PlatformResourceDescriptor(
        resource_key=resource_key,
        label=label,
        scope=scope,  # type: ignore[arg-type]
        backing_source=backing_source,
        queryable_fields=queryable_fields,
        filterable_fields=filterable_fields or [],
        sortable_fields=sortable_fields or [],
        relationships=relationships or [],
        default_limit=default_limit,
        freshness=freshness,
        required_role=required_role,  # type: ignore[arg-type]
        redacted_fields=redacted_fields or [],
        available_actions=available_actions or [],
        canonical_ui=canonical_ui,
        owner_module=owner_module,
        resolver=resolver,
        tags=tags,
        not_exposed_reason=not_exposed_reason,
    )


